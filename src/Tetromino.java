import java.awt.Color;
import java.util.Arrays;

/** 각 테트로미노의 색상과 네 가지 회전 상태의 칸 좌표를 보관한다. */
enum Tetromino {
    // 0도, 90도, 180도, 270도 순서.

    Imino(new Color(57, 205, 220), new int[][][] {
        {{0,1},{1,1},{2,1},{3,1}}, {{2,0},{2,1},{2,2},{2,3}},
        {{0,2},{1,2},{2,2},{3,2}}, {{1,0},{1,1},{1,2},{1,3}}
    }),
    Omino(new Color(245, 208, 66), new int[][][] {
        {{1,0},{2,0},{1,1},{2,1}}, {{1,0},{2,0},{1,1},{2,1}},
        {{1,0},{2,0},{1,1},{2,1}}, {{1,0},{2,0},{1,1},{2,1}}
    }),
    Tmino(new Color(170, 95, 220), new int[][][] {
        {{1,0},{0,1},{1,1},{2,1}}, {{1,0},{1,1},{2,1},{1,2}},
        {{0,1},{1,1},{1,2},{2,1}}, {{1,0},{0,1},{1,1},{1,2}}
    }),
    Smino(new Color(83, 195, 119), new int[][][] {
        {{1,0},{2,0},{0,1},{1,1}}, {{1,0},{1,1},{2,1},{2,2}},
        {{1,1},{2,1},{0,2},{1,2}}, {{0,0},{0,1},{1,1},{1,2}}
    }),
    Zmino(new Color(230, 83, 93), new int[][][] {
        {{0,0},{1,0},{1,1},{2,1}}, {{2,0},{1,1},{2,1},{1,2}},
        {{0,1},{1,1},{1,2},{2,2}}, {{1,0},{0,1},{1,1},{0,2}}
    }),
    Jmino(new Color(75, 125, 225), new int[][][] {
        {{0,0},{0,1},{1,1},{2,1}}, {{1,0},{2,0},{1,1},{1,2}},
        {{0,1},{1,1},{2,1},{2,2}}, {{1,0},{1,1},{0,2},{1,2}}
    }),
    Lmino(new Color(235, 151, 65), new int[][][] {
        {{2,0},{0,1},{1,1},{2,1}}, {{1,0},{1,1},{1,2},{2,2}},
        {{0,1},{1,1},{2,1},{0,2}}, {{0,0},{1,0},{1,1},{1,2}}
    });

    final Color color;

    private final int[][][] cells;

    Tetromino(Color color, int[][][] cells) { this.color = color; this.cells = cells; }

    int[][] cells(int rotation) { return Arrays.stream(cells[rotation & 3]).map(int[]::clone).toArray(int[][]::new); }
}
